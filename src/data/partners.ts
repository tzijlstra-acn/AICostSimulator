import { z } from "zod";

export const PartnerCategorySchema = z.enum([
  "cloud",
  "gpu_inference",
  "telecom",
  "si",
  "msp",
  "developer_tools",
  "data_analytics",
  "productivity",
  "security",
  "industry_software",
  "university_research",
  "marketplace",
  "reseller",
]);
export type PartnerCategory = z.infer<typeof PartnerCategorySchema>;

export const PartnerStageSchema = z.enum([
  "target",
  "outreach",
  "discovery",
  "pilot",
  "active",
  "signed",
]);
export type PartnerStage = z.infer<typeof PartnerStageSchema>;

export const PartnerSchema = z.object({
  id: z.string(),
  name: z.string(),
  category: PartnerCategorySchema,
  geography: z.array(z.string()),
  strategicFit: z.enum(["low", "medium", "high", "critical"]),
  infrastructureCapability: z.boolean(),
  regulatedIndustryReach: z.boolean(),
  commercialModel: z.string(),
  integrationStatus: z.string(),
  nextAction: z.string(),
  owner: z.string(),
  stage: PartnerStageSchema,
  notes: z.string().optional(),
  disclaimer: z.string().optional(),
  logoFile: z.string().optional(),
});

